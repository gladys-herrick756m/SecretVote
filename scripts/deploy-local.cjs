const { ethers } = require("hardhat");
const fs = require('fs');

async function main() {
  console.log("🚀 Starting local SecretVoteGovernance deployment...\n");

  // Get deployer account
  const [deployer] = await ethers.getSigners();
  console.log("📝 Deploying contracts with account:", deployer.address);
  console.log("💰 Account balance:", ethers.formatEther(await ethers.provider.getBalance(deployer.address)), "ETH\n");

  // For local testing, use deployer as both gateway and admin
  const gatewayAddress = deployer.address; // Mock gateway
  const adminAddress = deployer.address;

  console.log("👤 Admin address:", adminAddress);
  console.log("🔐 Gateway address (mock):", gatewayAddress, "\n");

  // Deploy contract
  console.log("📦 Deploying SecretVoteGovernance contract...");
  const SecretVoteGovernance = await ethers.getContractFactory("SecretVoteGovernance");
  const secretVote = await SecretVoteGovernance.deploy(gatewayAddress, adminAddress);

  await secretVote.waitForDeployment();
  const contractAddress = await secretVote.getAddress();

  console.log("✅ SecretVoteGovernance deployed to:", contractAddress);
  console.log("");

  // Verify deployment
  console.log("🔍 Verifying deployment...");
  const proposalCount = await secretVote.getProposalCount();
  console.log("   Initial proposal count:", proposalCount.toString());

  console.log("\n✨ Deployment completed successfully!\n");

  // Print deployment summary
  console.log("📋 Deployment Summary:");
  console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
  console.log("Contract Address:", contractAddress);
  console.log("Gateway Address:", gatewayAddress);
  console.log("Admin Address:", adminAddress);
  console.log("Network:", (await ethers.provider.getNetwork()).name);
  console.log("Chain ID:", (await ethers.provider.getNetwork()).chainId);
  console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

  // Grant roles for testing
  console.log("🔑 Granting roles for local testing...");
  const VOTER_ROLE = await secretVote.VOTER_ROLE();
  const PROPOSER_ROLE = await secretVote.PROPOSER_ROLE();

  // Grant roles to first 3 accounts
  const signers = await ethers.getSigners();
  try {
    for (let i = 0; i < Math.min(3, signers.length); i++) {
      const tx1 = await secretVote.grantRole(VOTER_ROLE, signers[i].address);
      await tx1.wait();
      const tx2 = await secretVote.grantRole(PROPOSER_ROLE, signers[i].address);
      await tx2.wait();
      console.log(`   ✓ Granted roles to account ${i}: ${signers[i].address}`);
    }
  } catch (error) {
    console.log(`   ⚠️ Role granting skipped (may already have roles): ${error.message}`);
  }

  // Save deployment info to file
  const deploymentInfo = {
    address: contractAddress,
    network: "localhost",
    chainId: Number((await ethers.provider.getNetwork()).chainId),
    gatewayAddress,
    adminAddress,
    deployedAt: new Date().toISOString(),
    accounts: signers.slice(0, 3).map((s, i) => ({
      index: i,
      address: s.address,
      roles: ["VOTER", "PROPOSER", i === 0 ? "ADMIN" : null].filter(Boolean)
    }))
  };

  fs.writeFileSync(
    './deployment-local.json',
    JSON.stringify(deploymentInfo, null, 2)
  );
  console.log("\n💾 Deployment info saved to deployment-local.json");

  // Save frontend config
  const frontendConfig = `// Auto-generated by deploy-local.cjs
export const CONTRACT_ADDRESS = "${contractAddress}";
export const CONTRACT_CHAIN_ID = ${deploymentInfo.chainId};
export const GATEWAY_ADDRESS = "${gatewayAddress}";

export const TEST_ACCOUNTS = ${JSON.stringify(deploymentInfo.accounts, null, 2)};
`;

  fs.writeFileSync(
    './src/config/contract.ts',
    frontendConfig
  );
  console.log("💾 Frontend config saved to src/config/contract.ts\n");

  console.log("\n📚 Next steps:");
  console.log("1. Start the frontend: npm run dev");
  console.log("2. Connect MetaMask to localhost:8545");
  console.log("3. Import test account private key:");
  console.log(`   Account #0: 0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80`);
  console.log("\n✅ Ready to test! The contract is deployed and configured.");

  return contractAddress;
}

main()
  .then((address) => {
    console.log("\n✅ Deployment script completed successfully");
    process.exit(0);
  })
  .catch((error) => {
    console.error("\n❌ Deployment failed:");
    console.error(error);
    process.exit(1);
  });
